#!/usr/bin/env node
// Copies the Anchor build artifacts into the publishable SDK so `@lath/sdk` needs no
// Anchor workspace at consume time. Run after `anchor build`; `--check` fails if stale.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const check = process.argv.includes("--check");

// No `anchor build` has run here — CI's frontend job, or a checkout that only builds the app —
// so there is nothing newer to copy and the committed `sdk/src/idl` is the IDL. A sync keeps it;
// `--check` still fails, because a check with no build to compare against has proven nothing.
if (!existsSync(resolve(root, "target/idl/lath.json"))) {
  if (check) {
    console.error("sync-idl --check: no target/idl/lath.json; run `anchor build` first");
    process.exit(1);
  }
  console.log("sync-idl: no target/ (no anchor build here); keeping the committed sdk/src/idl");
  process.exit(0);
}

const banner = "// Generated by sdk/scripts/sync-idl.mjs from target/. Do not edit by hand.\n";
const outputs = [];
// `lath_oracle` is not copied: the oracle is on the roadmap and not in this tree (it is deployed on
// devnet, untouched), so a `target/idl/lath_oracle.json` from another `anchor build` is neither
// required nor bundled.
for (const name of ["lath", "lath_billing"]) {
  const file = name.replace(/_/g, "-");
  outputs.push([resolve(here, `../src/idl/${file}.json`), readFileSync(resolve(root, `target/idl/${name}.json`), "utf8")]);
  outputs.push([
    resolve(here, `../src/idl/${file}-types.ts`),
    banner + readFileSync(resolve(root, `target/types/${name}.ts`), "utf8"),
  ]);
}

let stale = false;
for (const [path, content] of outputs) {
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === content) continue;
  stale = true;
  if (check) {
    console.error(`stale: ${path}`);
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}

if (check && stale) {
  console.error("sdk/src/idl is out of date; run `npm run sdk:sync` after `anchor build`");
  process.exit(1);
}
if (!stale) console.log("sdk/src/idl is up to date");
